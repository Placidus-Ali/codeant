# Variable declarations
first_name = "Alex"
last_name = "Doe"
age = 25
city = "Owerri"
hobby = "Coding"

# Printing variables on separate lines
print("--- Separate Lines ---")
print("First Name:", first_name)
print("Last Name:", last_name)
print("Age:", age)
print("City:", city)
print("Hobby:", hobby)

print()  # Blank line for clean spacing

# Printing using string concatenation (+)
print("--- String Concatenation ---")
print("My name is "+ first_name +" "+ last_name +". "+"I am " + str(age) + " years old, live in " + city + ", " + "and my hobby is " + hobby + ".")
